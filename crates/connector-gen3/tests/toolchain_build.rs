//! Builds in the hardened toolchain container (G3-002..G3-005): an edited trainer,
//! an edited map and a generated Poryscript scene build with `make`; a no-change
//! rebuild is faster than a clean one; build errors and test-runner results come
//! back as structured values.
//!
//! The container tests take minutes, so they run only with `TAUROS_DOCKER_TESTS=1`
//! (and the pinned expansion and toolchain image present); otherwise they skip.

mod common;

use std::fs;
use std::path::Path;
use std::process::Command;
use std::time::Instant;
use tauros_connector_gen3::toolchain::{Level, Toolchain};
use tauros_connector_gen3::Gen3Connector;
use tauros_model::*;

fn toolchain() -> Toolchain {
    Toolchain::for_repository(&common::repo_root()).unwrap()
}

/// The toolchain, or `None` (after printing why) when container tests are off.
fn docker() -> Option<Toolchain> {
    if std::env::var_os("TAUROS_DOCKER_TESTS").is_none() {
        eprintln!("SKIPPED: set TAUROS_DOCKER_TESTS=1 to run the container build tests (they take minutes)");
        return None;
    }
    let tc = toolchain();
    let present = Command::new("docker").args(["image", "inspect", &tc.image]).output().is_ok_and(|o| o.status.success());
    if !present {
        eprintln!("SKIPPED: image {} missing; run `python3 scripts/setup_toolchain.py`", tc.image);
        return None;
    }
    Some(tc)
}

#[test]
fn hardened_options_match_setup_toolchain() {
    let tc = toolchain();
    let workdir = Path::new("/some/project");
    let script = "make -j4 rom syms";
    let python = Command::new("python3")
        .current_dir(common::repo_root())
        .args([
            "-c",
            "import json, sys; from pathlib import Path; sys.path.insert(0, 'scripts'); import setup_toolchain as s; \
             m = s.load_manifest(); print(s.image_tag(m)); print(json.dumps(s.hardened_run(s.image_tag(m), sys.argv[1], Path(sys.argv[2]))))",
            script,
            "/some/project",
        ])
        .output()
        .unwrap();
    assert!(python.status.success(), "{}", String::from_utf8_lossy(&python.stderr));
    let out = String::from_utf8(python.stdout).unwrap();
    let mut lines = out.lines();
    assert_eq!(lines.next().unwrap(), tc.image, "image tag differs from setup_toolchain.py");
    let expected: Vec<String> = tauros_connector_gen3::json::Document::parse(lines.next().unwrap())
        .unwrap()
        .root
        .as_array()
        .unwrap()
        .items
        .iter()
        .map(|i| i.node.as_str().unwrap())
        .collect();
    assert_eq!(tc.hardened_args(Some(workdir), script), expected);
}

const SCENE: &str = "Route101_EventScript_TaurosScene";

fn scene_source() -> String {
    format!(
        "script {SCENE} {{\n    lock\n    faceplayer\n    if (flag(FLAG_TAUROS_SCENE_DONE)) {{\n        msgbox(\"You already saw the Tauros scene.\")\n    }} else {{\n        msgbox(\"This scene was generated by Tauros.\")\n        setflag(FLAG_TAUROS_SCENE_DONE)\n    }}\n    release\n    end\n}}\n"
    )
}

#[test]
fn edited_project_builds_incrementally_with_structured_results() {
    let Some(engine) = common::engine() else { return };
    let Some(tc) = docker() else { return };
    let dir = common::fixture(&engine, "g3-build", &[]);
    let mut c = Gen3Connector::open(dir.path(), Some(tc.clone())).unwrap();
    let before = c.load().unwrap();

    // Poryscript errors come back as a message, not a panic or a write.
    let err = tc.compile_poryscript("script Broken {\n    msgbox(\n}\n").unwrap_err();
    eprintln!("poryscript error: {err}");
    assert!(!err.is_empty());

    // One change set: a trainer edit (G3-002), an NPC (G3-003), a flag and a
    // Poryscript scene using it (G3-004).
    let mut roxanne = before.trainers[&TrainerId::from("TRAINER_ROXANNE_1")].clone();
    roxanne.party.members[0].level += 1;
    let new_level = roxanne.party.members[0].level;
    let npc = Event::Npc {
        local_id: None,
        graphics: "OBJ_EVENT_GFX_BOY_1".into(),
        position: Position { x: 12, y: 10, elevation: Some(3) },
        movement: Some("MOVEMENT_TYPE_FACE_DOWN".into()),
        script: Some(ScriptLabel::from(SCENE)),
        visibility_flag: None,
        extensions: [
            ("movement_range_x".to_owned(), Value::Int(0)),
            ("movement_range_y".to_owned(), Value::Int(0)),
            ("trainer_type".to_owned(), Value::Text("TRAINER_TYPE_NONE".into())),
            ("trainer_sight_or_berry_tree_id".to_owned(), Value::Text("0".into())),
        ]
        .into(),
    };
    let scene = Scene {
        label: ScriptLabel::from(SCENE),
        map: Some(MapId::from("MAP_ROUTE101")),
        language: ScriptLanguage::Poryscript,
        source: scene_source(),
    };
    let set = ChangeSet::new("Tauros demo scene on Route 101", Provenance::AiAssisted)
        .with(Change::AllocateFlag { id: FlagId::from("FLAG_TAUROS_SCENE_DONE") })
        .with(Change::UpsertTrainer { trainer: roxanne.clone() })
        .with(Change::AddEvent { map: MapId::from("MAP_ROUTE101"), event: npc })
        .with(Change::UpsertScene { scene: scene.clone() });
    let applied = c.apply(&set).unwrap();
    eprintln!("touched: {:?}", applied.touched);
    assert_eq!(
        applied.touched,
        [
            "data/event_scripts.s",
            "data/maps/Route101/map.json",
            "data/maps/Route101/scenes/Route101_EventScript_TaurosScene.inc",
            "data/maps/Route101/scenes/Route101_EventScript_TaurosScene.pory",
            "include/constants/flags.h",
            "src/data/trainers.party",
        ]
    );
    let loaded = c.load().unwrap();
    assert_eq!(loaded.scenes[&scene.label], scene);
    assert!(loaded.flags[&FlagId::from("FLAG_TAUROS_SCENE_DONE")].in_use);
    let compiled = fs::read_to_string(dir.path().join("data/maps/Route101/scenes/Route101_EventScript_TaurosScene.inc")).unwrap();
    eprintln!("compiled scene:\n{compiled}");
    assert!(compiled.contains(&format!("{SCENE}::")));

    // Clean build, then a no-change rebuild.
    let start = Instant::now();
    let out = c.build().unwrap_or_else(|e| panic!("build failed: {e:?}"));
    let clean = start.elapsed();
    let start = Instant::now();
    let report = c.build_report().unwrap();
    let noop = start.elapsed();
    assert!(report.success);
    eprintln!("clean build {:.1}s, no-change rebuild {:.1}s, rom sha256 {}", clean.as_secs_f64(), noop.as_secs_f64(), out.rom_sha256);
    assert!(noop * 5 < clean, "no-change rebuild is not measurably faster");
    assert!(out.rom.is_file() && out.symbols.as_ref().is_some_and(|s| s.is_file()));
    let base = fs::read_to_string(engine.parent().unwrap().join(format!("{}-base/tauros-base-build.json", engine.file_name().unwrap().to_string_lossy()))).unwrap();
    assert!(!base.contains(&out.rom_sha256), "the edited ROM equals the base ROM");

    // The edits are in the build: the scene is linked, the trainer table has the level.
    let syms = fs::read_to_string(out.symbols.unwrap()).unwrap();
    assert!(syms.lines().any(|l| l.ends_with(&format!(" {SCENE}"))), "scene label not linked");
    let trainers_h = fs::read_to_string(dir.path().join("src/data/trainers.h")).unwrap();
    let roxanne_h = &trainers_h[trainers_h.find("[TRAINER_ROXANNE_1]").unwrap()..];
    assert!(roxanne_h[..roxanne_h.find(".lvl").map(|i| i + 20).unwrap()].contains(&format!(".lvl = {new_level},")));
    let events = fs::read_to_string(dir.path().join("data/maps/Route101/events.inc")).unwrap();
    assert!(events.contains(SCENE), "NPC not in the generated map events");

    // A broken trainer file is reported with file and line.
    let party = dir.path().join("src/data/trainers.party");
    let good = fs::read_to_string(&party).unwrap();
    let bad_line = good[..good.find("=== TRAINER_SAWYER_1 ===").unwrap()].lines().count() + 3;
    fs::write(&party, good.replacen("=== TRAINER_SAWYER_1 ===\nName: SAWYER\n", "=== TRAINER_SAWYER_1 ===\nName: SAWYER\nBogus Key: 1\n", 1)).unwrap();
    let err = c.build().unwrap_err();
    let ConnectorError::Build(diagnostics) = &err else { panic!("{err:?}") };
    eprintln!("build diagnostics: {diagnostics:#?}");
    assert!(diagnostics.iter().any(|d| d.file.as_deref() == Some("src/data/trainers.party") && d.line == Some(bad_line as u32)));
    // And a C error with file, line and column.
    fs::write(&party, &good).unwrap();
    let main = dir.path().join("src/main.c");
    let main_text = fs::read_to_string(&main).unwrap();
    fs::write(&main, format!("{main_text}\nint gTaurosBroken = ;\n")).unwrap();
    let report = c.build_report().unwrap();
    assert!(!report.success);
    let error = report.errors().find(|d| d.file.as_deref() == Some("src/main.c")).expect("C error located");
    eprintln!("C error: {error:?}");
    assert_eq!((error.level, error.line), (Level::Error, Some(main_text.lines().count() as u32 + 2)));
    assert!(error.column.is_some());
    fs::write(&main, &main_text).unwrap();

    // The expansion's headless test runner, filtered, parsed into results.
    let tests = tc.run_tests(dir.path(), Some("Trainer Party")).unwrap();
    eprintln!("test runner: {:?} in {:.1}s", tests.totals, tests.duration.as_secs_f64());
    for case in &tests.cases {
        eprintln!("  [{}] {}: {}", case.runner, case.name, case.result);
    }
    assert!(tests.success);
    assert!(!tests.cases.is_empty() && tests.cases.iter().all(|t| t.passed()));
    assert_eq!(tests.totals.get("PASSED"), Some(&(tests.cases.len() as u32)));
    assert_eq!(tests.totals.get("TOTAL"), Some(&(tests.cases.len() as u32)));
}
